/**
 * Runs after `expo export --platform web`: writes dist/sw.js, a service worker that
 * precaches the app shell so the app opens and works fully offline after the first visit.
 * User progress lives in localStorage, so it is never affected by cache updates.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const BASE = process.env.BASE_PATH || '';
const dist = path.resolve(__dirname, '..', 'dist');
if (!fs.existsSync(dist)) {
  console.error('dist/ not found. Run `expo export --platform web` first.');
  process.exit(1);
}

// Only the fonts the app really uses are precached; anything else is cached on demand.
const USED_FONT = /(Inter_(400Regular|500Medium|600SemiBold|700Bold)|Feather)\.[0-9a-f]+\.ttf$/;
const SKIP = [/\.map$/, /(^|\/)\.[^/]+$/, /(^|\/)sw\.js$/, /^_sitemap\.html$/, /^\(tabs\)\//];

function walk(dir, base = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    return entry.isDirectory() ? walk(path.join(dir, entry.name), rel) : [rel];
  });
}

const files = walk(dist)
  .filter((rel) => !SKIP.some((re) => re.test(rel)))
  .filter((rel) => !rel.endsWith('.ttf') || USED_FONT.test(rel))
  .sort();

const hash = crypto.createHash('sha1');
for (const rel of files) hash.update(rel).update(fs.readFileSync(path.join(dist, rel)));
const version = hash.digest('hex').slice(0, 12);

const sw = `/* Generated by scripts/postbuild-web.js — do not edit. */
const CACHE = 'conduce-${version}';
const BASE = ${JSON.stringify(BASE)};
const PRECACHE = ${JSON.stringify(files.map((rel) => `${BASE}/${rel}`), null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('conduce-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

async function page(url) {
  const cache = await caches.open(CACHE);
  const path = url.pathname.slice(BASE.length).replace(/\\/+$/, '') || '/index';
  for (const candidate of [BASE + path + '.html', BASE + path + '/index.html', BASE + '/index.html']) {
    const hit = await cache.match(candidate);
    if (hit) return hit;
  }
  return fetch(url);
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(page(url));
    return;
  }
  event.respondWith(
    caches.match(request).then((hit) => hit || fetch(request).then((response) => {
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return response;
    })),
  );
});
`;

fs.writeFileSync(path.join(dist, 'sw.js'), sw);

if (BASE) {
  const file = path.join(dist, 'manifest.webmanifest');
  const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  manifest.start_url = `${BASE}/`;
  manifest.scope = `${BASE}/`;
  manifest.id = `${BASE}/`;
  manifest.icons = manifest.icons.map((icon) => ({ ...icon, src: `${BASE}${icon.src}` }));
  fs.writeFileSync(file, JSON.stringify(manifest, null, 2));
}
const bytes = files.reduce((sum, rel) => sum + fs.statSync(path.join(dist, rel)).size, 0);
console.log(`sw.js: ${files.length} files precached (${(bytes / 1048576).toFixed(1)} MB), version ${version}`);
